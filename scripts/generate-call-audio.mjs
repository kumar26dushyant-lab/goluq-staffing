/**
 * Generates the mock-call audio clips.
 *
 *   GEMINI_API_KEY=xxxxx node scripts/generate-call-audio.mjs
 *   GEMINI_API_KEY=xxxxx node scripts/generate-call-audio.mjs voice clinic   # one combo
 *   ROLES=voice,reception GEMINI_API_KEY=xxxxx node scripts/generate-call-audio.mjs
 *
 * Uses the **Gemini TTS model with the GEMINI_API_KEY the app already has** —
 * no separate Google Cloud project, no billing setup, no extra API to enable.
 * Gemini returns raw 24kHz PCM, which ffmpeg converts to MP3 (present on both
 * the dev machine and the server).
 *
 * Only the VOICE role is generated by default: it is the only role that plays
 * audio (chat roles render as message bubbles), so generating the rest would
 * spend tokens on files nothing ever fetches.
 *
 * Output: public/audio/<lang>/<role>-<industry>/<n>.mp3 — one clip per turn, so
 * captions stay in sync with no timing metadata and a missing clip degrades to
 * the device voice instead of breaking the call (see src/lib/callAudio.ts).
 *
 * Re-run any time src/content/dialogues.ts changes. Existing files are skipped
 * unless FORCE=1.
 */
import { mkdirSync, existsSync, writeFileSync, readFileSync, unlinkSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "public", "audio");
const KEY = process.env.GEMINI_API_KEY;
const FORCE = process.env.FORCE === "1";
const MODEL = process.env.TTS_MODEL || "gemini-2.5-flash-preview-tts";

if (!KEY) {
  console.error(
    "GEMINI_API_KEY is not set.\n" +
      "It is the same key the site already uses — on the server:\n" +
      "  set -a; . /opt/goluq/.env; set +a; node scripts/generate-call-audio.mjs"
  );
  process.exit(1);
}

/**
 * Two clearly different voices so a listener can tell who is speaking without
 * looking at the screen. Gemini's prebuilt voices are language-agnostic, so the
 * same worker voice carries across Hindi, Marathi and English — which keeps the
 * "employee" recognisable when a visitor switches language.
 */
const VOICE = { agent: "Kore", caller: "Charon" };

/** Delivery direction — Gemini TTS follows a plain-language style instruction. */
const STYLE = {
  agent:
    "Say this warmly and professionally, like an experienced receptionist on a phone call. Calm, unhurried, clearly articulated:",
  caller:
    "Say this like an ordinary person calling a business on the phone — natural, slightly hurried, conversational:",
};

const LANGS = (process.env.LANGS || "hi,en,mr").split(",");
const ROLES = (process.env.ROLES || "voice").split(",");
const INDUSTRIES = ["clinic", "diagnostic", "coaching", "ca", "travel"];

// dialogues.ts is TypeScript — bundle it to plain ESM first. Uses esbuild's JS
// API rather than its CLI, because spawning npx is unreliable on Windows.
const TMP = join(ROOT, "node_modules", ".cache", "goluq-dialogues.mjs");
mkdirSync(dirname(TMP), { recursive: true });
const esbuild = await import("esbuild");
await esbuild.build({
  entryPoints: [join(ROOT, "src", "content", "dialogues.ts")],
  bundle: true,
  format: "esm",
  platform: "node",
  outfile: TMP,
  logLevel: "error",
});
const { getDialogue, line } = await import(pathToFileURL(TMP).href);

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** Gemini TTS -> raw PCM. Retries on rate limiting rather than dying mid-run. */
async function synth(text, who, attempt = 0) {
  const res = await fetch(
    `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent?key=${KEY}`,
    {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        contents: [{ parts: [{ text: `${STYLE[who]} ${text}` }] }],
        generationConfig: {
          responseModalities: ["AUDIO"],
          speechConfig: {
            voiceConfig: { prebuiltVoiceConfig: { voiceName: VOICE[who] } },
          },
        },
      }),
    }
  );

  if (res.status === 429 && attempt < 5) {
    const wait = 5000 * (attempt + 1);
    process.stdout.write(`    rate limited, waiting ${wait / 1000}s…\n`);
    await sleep(wait);
    return synth(text, who, attempt + 1);
  }
  if (!res.ok) throw new Error(`TTS ${res.status}: ${(await res.text()).slice(0, 300)}`);

  const json = await res.json();
  const inline = json?.candidates?.[0]?.content?.parts?.[0]?.inlineData;
  if (!inline?.data) {
    // Short utterances sometimes come back empty with finishReason OTHER.
    if (attempt < 3) {
      await sleep(1500);
      return synth(text, who, attempt + 1);
    }
    throw new Error(`no audio after retries (finishReason: ${json?.candidates?.[0]?.finishReason})`);
  }
  return Buffer.from(inline.data, "base64");
}

/**
 * 24kHz mono PCM -> MP3. Kept clean rather than run through a telephony filter:
 * the visitor is judging whether it sounds human, and band-limiting only hurts
 * that impression even though it would be more "authentic".
 */
function pcmToMp3(pcm, outFile) {
  const raw = join(tmpdir(), `goluq-tts-${process.pid}.pcm`);
  writeFileSync(raw, pcm);
  execFileSync(
    "ffmpeg",
    ["-y", "-f", "s16le", "-ar", "24000", "-ac", "1", "-i", raw,
     "-codec:a", "libmp3lame", "-b:a", "64k", outFile],
    { stdio: "pipe" }
  );
  unlinkSync(raw);
  return readFileSync(outFile).length;
}

const [argRole, argIndustry] = process.argv.slice(2);
let made = 0, skipped = 0, bytes = 0;
const failed = [];

for (const role of ROLES) {
  if (argRole && role !== argRole) continue;
  for (const industry of INDUSTRIES) {
    if (argIndustry && industry !== argIndustry) continue;
    const dialogue = getDialogue(role, industry);

    for (const lang of LANGS) {
      const dir = join(OUT, lang, `${role}-${industry}`);
      mkdirSync(dir, { recursive: true });

      for (let i = 0; i < dialogue.turns.length; i++) {
        const file = join(dir, `${i}.mp3`);
        const turn = dialogue.turns[i];

        // No real Marathi line -> skip; the player falls back to the Hindi clip,
        // which beats a Marathi voice reading Hindi text.
        if (lang === "mr" && !turn.mr) { skipped++; continue; }
        if (existsSync(file) && !FORCE) { skipped++; continue; }

        try {
          const pcm = await synth(line(turn, lang), turn.who);
          bytes += pcmToMp3(pcm, file);
          made++;
          process.stdout.write(`  ${lang}/${role}-${industry}/${i}.mp3\n`);
        } catch (err) {
          console.error(`\nFailed on ${lang}/${role}-${industry}/${i}.mp3`);
          console.error(String(err.message || err));
          console.error("\nNothing was lost — re-run and it resumes where it stopped.");
          esbuild.stop?.();
          process.exit(1);
        }
        await sleep(1100); // stay inside the per-minute quota
      }
    }
  }
}

console.log(
  `\nDone. ${made} clip(s) written (${(bytes / 1024 / 1024).toFixed(1)} MB), ${skipped} skipped.`
);
if (failed.length) {
  console.log(`
${failed.length} clip(s) could not be generated and will use the device
voice instead: ${failed.join(", ")}`);
  console.log("Re-run to retry just those.");
}
console.log("Commit public/audio/ and deploy — the call upgrades automatically.");
esbuild.stop?.();
